    /** Усі блоки: ключ => опис */
    public static function all(): array { return self::BLOCKS; }

    public static function has(string $key): bool { return isset(self::BLOCKS[$key]); }

    public static function block(string $key): ?array { return self::BLOCKS[$key] ?? null; }

    public static function label(string $key): string { return self::BLOCKS[$key]['label'] ?? $key; }

    public static function where(string $key): string { return self::BLOCKS[$key]['where'] ?? ''; }

    /** Поля блоку: назва колонки => опис поля */
    public static function fields(string $key): array { return self::BLOCKS[$key]['fields'] ?? []; }

    /** Опис одного поля або null, якщо такого поля в блоці немає */
    public static function field(string $key, string $field): ?array
    {
        return self::BLOCKS[$key]['fields'][$field] ?? null;
    }

    public static function type(string $key, string $field): ?string
    {
        return self::BLOCKS[$key]['fields'][$field]['type'] ?? null;
    }

    /** Чи значення поля зберігається як JSON (списки), а не як текст */
    public static function isList(string $key, string $field): bool
    {
        return in_array(self::type($key, $field) ?? '', self::JSON_TYPES, true);
    }

    /** Блоки, згруповані за сторінкою: назва групи => [ключі] */
    public static function groups(): array
    {
        $out = [];
        foreach (self::BLOCKS as $key => $def) $out[$def['group']][] = $key;
        return $out;
    }
}

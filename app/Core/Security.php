<?php
declare(strict_types=1);

/**
 * Заголовки безпеки: що браузеру дозволено робити на наших сторінках.
 *
 * Це другий рубіж, а не перший. Перший — те, що ми взагалі не пускаємо чужий
 * текст у HTML: усе йде через `e()`, а те, що потрапляє всередину <script>, —
 * через `json_js()`. Заголовки нижче обмежують шкоду, якщо перший рубіж десь
 * дав збій: навіть маючи змогу вставити тег, зловмисник не зможе ані вивести
 * дані на свій домен, ані підмінити базовий шлях сторінки.
 *
 * Тому вони мають сенс саме на сайті, який уже написаний акуратно, — це не
 * заміна екранування, а страховка від однієї пропущеної дужки.
 */
class Security
{
    /**
     * Домени, з яких сторінці дозволено вантажити чуже.
     *
     * Список навмисно короткий і перелічений поіменно. Кожен рядок тут — це
     * дозвіл виконати чужий код у наших відвідувачів, тож він має зʼявлятись
     * разом із функцією, якій потрібен, і зникати разом із нею.
     */
    private const MAPS = 'https://maps.googleapis.com https://maps.gstatic.com';
    private const MAPS_IMG = 'https://maps.googleapis.com https://maps.gstatic.com '
        . 'https://khms0.googleapis.com https://khms1.googleapis.com https://*.ggpht.com';
    /** Превʼю відео на головній і в «Соцмережах» — саме цей домен будує YouTube::latest() */
    private const YT_IMG = 'https://i.ytimg.com';

    public static function headers(): void
    {
        // Заголовки має сенс слати лише коли відповідь ще не пішла: у CLI й
        // тестах headers_sent() true, і PHP інакше сипав би попередженнями
        if (headers_sent()) return;

        // Браузер не має «здогадуватись» про тип файлу. Без цього завантажене
        // фото, яке хтось зумів підсунути з HTML усередині, може бути показане
        // як сторінка — попри те, що ми віддали його як картинку.
        header('X-Content-Type-Options: nosniff');

        // Сайт у чужому фреймі — це клікджекінг: поверх невидимої адмінки
        // кладуть свою сторінку, і людина натискає «Видалити», думаючи, що
        // натискає щось інше. frame-ancestors — сучасна форма, X-Frame-Options
        // лишаємо для старих браузерів, які CSP не читають.
        header('X-Frame-Options: DENY');

        // Куди тече адреса нашої сторінки при переході за посиланням. Повний
        // шлях лишається всередині сайту, назовні йде лише домен: інакше
        // адміністратор, клацнувши посилання на товар постачальника, віддав би
        // тому адресу сторінки адмінки з номером замовлення.
        header('Referrer-Policy: strict-origin-when-cross-origin');

        // Можливості, яких сайту не треба. Камера — виняток: нею читають
        // штрихкоди на касі й на екрані кодів, і лише з нашого ж домену.
        header('Permissions-Policy: camera=(self), microphone=(), geolocation=(), '
            . 'payment=(), usb=(), interest-cohort=()');

        header('Content-Security-Policy: ' . self::csp());

        // HSTS вимикає можливість зайти по http узагалі — і памʼятається
        // браузером місяцями. Тому лише за явним увімкненням у config.local.php:
        // на спільному хостингу заголовок діє на весь домен, і сусідній сайт,
        // не готовий до HTTPS, ним можна покласти.
        if (cfg('hsts') && self::https()) {
            header('Strict-Transport-Security: max-age=15552000');   // 180 днів, без preload
        }
    }

    /**
     * Політика вмісту.
     *
     * `script-src` поки що з 'unsafe-inline': у шаблонах вісімнадцять
     * інлайнових <script> і два десятки onclick, і без них політика просто
     * поклала б сайт. Це чесно означає, що від виконання вставленого скрипта
     * CSP тут ще не рятує — рятує решта директив, і вони не декоративні:
     *
     *   base-uri     — не дає підмінити <base> і тим самим перенаправити всі
     *                  відносні шляхи сторінки на чужий домен;
     *   form-action  — вставлена форма не відправить пароль чи адресу назовні;
     *   object-src   — прибирає цілий клас старих векторів через плагіни;
     *   connect-src  — навіть виконаний скрипт не має куди відіслати вкрадене.
     *
     * Шлях до строгої політики описаний у README: нонси на кожен <script> і
     * перенесення onclick у обробники. Це помітний обсяг правок у шаблонах,
     * і робити його наосліп перед переїздом на бойовий сервер небезпечніше,
     * ніж лишити цю директиву слабкою й позначеною.
     */
    private static function csp(): string
    {
        $self = "'self'";
        return implode('; ', [
            "default-src $self",
            "script-src $self 'unsafe-inline' " . self::MAPS,
            "style-src $self 'unsafe-inline'",
            // data: — вбудовані іконки в CSS; blob: — кадр із камери під час сканування
            "img-src $self data: blob: " . self::MAPS_IMG . ' ' . self::YT_IMG,
            "font-src $self",
            "connect-src $self " . self::MAPS,
            "media-src $self blob:",          // потік із камери
            "worker-src $self blob:",         // service worker (PWA) і декодер коду
            "frame-src 'none'",
            "object-src 'none'",
            "base-uri $self",
            "form-action $self",
            "frame-ancestors 'none'",
        ]);
    }

    /** Той самий спосіб визначення, що й у куці сесії (Auth::start) */
    public static function https(): bool
    {
        if (!empty($_SERVER['HTTPS']) && $_SERVER['HTTPS'] !== 'off') return true;
        // Заголовку від проксі віримо лише тоді, коли проксі справді є: інакше
        // його підробляє будь-хто, і ми вважаємо http-зʼєднання захищеним
        return cfg('trust_proxy') && ($_SERVER['HTTP_X_FORWARDED_PROTO'] ?? '') === 'https';
    }
}
